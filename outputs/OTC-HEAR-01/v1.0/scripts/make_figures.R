suppressPackageStartupMessages(library(data.table))
argfile<-sub("^--file=","",commandArgs(FALSE)[grep("^--file=",commandArgs(FALSE))])
root<-normalizePath(file.path(dirname(argfile),"../../../.."));out<-file.path(root,"outputs/OTC-HEAR-01/v1.0")
event<-fread(file.path(out,"L2/event_study.csv"));main<-fread(file.path(out,"L2/main_estimate.csv"))
dir.create(file.path(out,"figures"),showWarnings=FALSE)
draw<-function(){
 layout(matrix(c(1,2),1,2),widths=c(2.1,1.05));par(family="sans",las=1,fg="#253342",col.axis="#526273",col.lab="#253342",cex=.9)
 par(mar=c(5.8,4.5,3.7,1.3))
 x<-event$year+.5;x[event$year==2022]<-2022.375
 plot(x,event$estimate_pp,type="n",xlim=c(2019.15,2025.85),ylim=c(28,35.4),xaxt="n",yaxt="n",bty="l",xlab="",ylab="Standardized hearing aid use (%)")
 abline(h=seq(28,35,1),col="#e9edf2",lwd=.7);axis(1,at=2019:2025+.5,labels=2019:2025,tck=-.015);axis(2,at=28:35,tck=-.015)
 rect(2022.75,28,2023,35.4,col="#e9edf277",border=NA)
 abline(v=2022+289/365,col="#8c98a4",lty=3,lwd=1)
 for(idx in list(which(event$year%in%c(2019,2021,2022)),which(event$year%in%c(2023,2024))))lines(x[idx],event$estimate_pp[idx],col="#236b8e",lwd=1.5)
 colors<-ifelse(event$year==2020,"#89949f",ifelse(event$year==2025,"#b56a29","#236b8e"))
 arrows(x,event$ci_lower_pp,x,event$ci_upper_pp,angle=90,code=3,length=.035,col=colors,lwd=1)
 points(x,event$estimate_pp,pch=ifelse(event$year==2020,1,ifelse(event$year==2025,18,16)),cex=1.05,col=colors)
 title(main="Annual estimates",adj=0,cex.main=1.2,font.main=2,line=1.5)
 legend("topleft",legend=c("Main-window years","2020: display only","2025: separate extension"),pch=c(16,1,18),col=c("#236b8e","#89949f","#b56a29"),bty="n",cex=.75,inset=c(0,.015))
 mtext("2022 estimate uses January-September. Bars show design-adjusted 95% CIs.",side=1,line=3.2,cex=.67,adj=0)
 mtext("Dashed line: OTC rule effective October 17, 2022.",side=1,line=4.35,cex=.67,adj=0)
 par(mar=c(5.8,2.4,3.7,1.7))
 plot(0,0,type="n",xlim=c(-3.7,3.7),ylim=c(.5,1.9),xaxt="n",yaxt="n",bty="n",xlab="",ylab="")
 rect(-2.5,.72,2.5,1.45,col="#e5f1f2",border=NA);segments(0,.72,0,1.45,col="#9ca7b0",lwd=.7);segments(c(-2.5,2.5),.72,c(-2.5,2.5),1.45,col="#8fb9bc",lty=3)
 segments(main$ci_lower_pp,1.08,main$ci_upper_pp,1.08,lwd=2.2,col="#236b8e");segments(c(main$ci_lower_pp,main$ci_upper_pp),1.02,c(main$ci_lower_pp,main$ci_upper_pp),1.14,lwd=1.4,col="#236b8e");points(main$estimate_pp,1.08,pch=16,col="#236b8e",cex=1.1)
 axis(1,at=c(-2.5,0,2.5),labels=c("-2.5","0","+2.5"),pos=.72,tck=-.025)
 mtext("Post - pre (percentage points)",side=1,line=1.7,cex=.85)
 text(0,1.7,sprintf("%+.2f pp",main$estimate_pp),cex=1.65,font=2,col="#236b8e")
 text(0,1.51,sprintf("95%% CI %.2f to %+.2f",main$ci_lower_pp,main$ci_upper_pp),cex=.82)
 title(main="Primary change",adj=0,cex.main=1.2,font.main=2,line=1.5)
 mtext("Shaded range: frozen equivalence margin.",side=1,line=3.2,cex=.67,adj=0)
 mtext("A period comparison; no causal policy attribution.",side=1,line=4.35,cex=.67,adj=0)
}
pdf(file.path(out,"figures/OTC_HEAR_01_main_event.pdf"),width=11.2,height=4.8,useDingbats=FALSE);draw();dev.off()
svg(file.path(out,"figures/OTC_HEAR_01_main_event.svg"),width=11.2,height=4.8);draw();dev.off()
png(file.path(out,"figures/OTC_HEAR_01_main_event.png"),width=2240,height=960,res=200,type="cairo");draw();dev.off()
